test('topic deletion confirms, cancels with keyboard focus, and then shows tombstone', async () => {
  mount('/clubs/c/discussions/d'); await screen.findByText(comment.body)
  await userEvent.click(screen.getByRole('button', { name: 'Видалити тему' }))
  const dialog = screen.getByRole('alertdialog')
  expect(within(dialog).getByRole('button', { name: 'Скасувати' })).toHaveFocus()
  await userEvent.keyboard('{Escape}')
  expect(screen.getByRole('button', { name: 'Видалити тему' })).toHaveFocus()
  expect(discussionService.remove).not.toHaveBeenCalled()
  await userEvent.click(screen.getByRole('button', { name: 'Видалити тему' }))
  discussionService.get.mockResolvedValue({ id: 'd', club_id: 'c', deleted_at: topic.updated_at })
  await userEvent.click(screen.getByRole('button', { name: 'Підтвердити' }))
  await screen.findByText('Тему видалено. Її текст і коментарі недоступні.')
  expect(screen.queryByText(comment.body)).not.toBeInTheDocument()
  expect(screen.queryByText(/Перший рядок/)).not.toBeInTheDocument()
})
