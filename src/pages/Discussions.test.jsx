test('account switch aborts reads and cannot display late response from old account', async () => {
  let done
  discussionService.get.mockImplementationOnce(() => new Promise((resolve) => { done = resolve }))
  const view = mount('/clubs/c/discussions/d')
  await waitFor(() => expect(discussionService.get).toHaveBeenCalled())
  const signal = discussionService.get.mock.calls[0][1].signal
  useAuth.mockReturnValue({ user: { id: 'other', role: 'user' }, status: 'ready' })
  discussionService.get.mockRejectedValue(new ServiceError('Доступ втрачено'))
  view.rerender(<MemoryRouter initialEntries={['/clubs/c/discussions/d']}><App /></MemoryRouter>)
  await screen.findByText('Доступ втрачено')
  await act(async () => done(topic))
  expect(signal.aborted).toBe(true)
  expect(screen.queryByText(/Перший рядок/)).not.toBeInTheDocument()
  expect(discussionService.comments).not.toHaveBeenCalled()
})
